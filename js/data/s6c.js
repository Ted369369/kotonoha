《Fate/Zero》裡那個膽小的少年韋伯，十年後成了時計塔的講師「羅德・艾梅洛二世」。這部作品把魔術和推理結合在一起：魔術可以讓「怎麼做到的」和「是誰做的」都變得不可靠，於是推理的重點落在別的地方。讀它，也順便學推理小說的日文：

