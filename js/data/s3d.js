  title: '帶著感情的原因：おかげで・せいで・ばかりに・からには・だけに',
  lead: '同樣是「因為」，日文會在裡面裝進感情：好結果說「多虧」，壞結果說「都怪」，後悔時說「就只因為」，下定決心時說「既然」。這一課的句型，讓你聽出角色說「因為」時真正的心情。',
