  title: '範圍與追加：だけでなく・ばかりか・どころか・に限って・に限らず',
  lead: '「不只……還……」「別說……了，連……都」「偏偏在這種時候」——這一組句型負責把話的範圍擴大、縮小，或是在最糟糕的時刻插上一句抱怨。',
